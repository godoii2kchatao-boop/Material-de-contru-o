// Domain types shared by the storefront, the admin and the data layer.

export type Availability = 'em_estoque' | 'sob_encomenda' | 'consulte' | 'indisponivel';
export type FreightClass = 'leve' | 'volumoso' | 'granel';

export interface Category {
  slug: string;
  name: string;
  description: string;
  order: number;
  active?: boolean;
}

export interface Product {
  id: string;
  slug: string;
  sku: string;
  name: string;
  category: string;
  brand: string | null;
  unit: string;
  minQty: number;
  /** Demo price in cents, or null for "sob consulta". */
  priceCents: number | null;
  availability: Availability;
  description: string;
  specs: Record<string, string>;
  applications: string[];
  /** Product photograph (store upload or licensed illustrative photo), or null: the category tile is shown. */
  image: string | null;
  imageAlt?: string | null;
  /** Set for licensed stand-in photos: shown as "Foto ilustrativa" with its credit. */
  imageCredit?: ImageCredit | null;
  popular: boolean;
  freightClass: FreightClass;
  active: boolean;
  updatedAt: string;
}

export type OfferKind = 'semanal' | 'combo' | 'kit' | 'categoria' | 'sazonal' | 'destaque';

export interface ImageCredit {
  author: string;
  license: string;
  source: string;
}

export interface Offer {
  id: string;
  title: string;
  description: string;
  kind: OfferKind;
  productIds: string[];
  /** Price for the whole offer (combo/kit) or per unit, in cents. Null shows "sob consulta". */
  priceCents: number | null;
  /** Reference price shown crossed out ONLY when the store registered it. */
  referencePriceCents: number | null;
  category?: string | null;
  startsAt: string; // ISO date
  endsAt: string; // ISO date
  active: boolean;
}

export interface Region {
  id: string;
  name: string;
  cities: string[];
  /** Inclusive ranges of the first five CEP digits, e.g. ['13050', '13069']. */
  cepRanges: [string, string][];
  neighborhoods: string[];
  baseFeeCents: number;
  bulkyFeeCents: number;
  leadTime: string;
  active: boolean;
}

export type CustomerProfile =
  | 'morador'
  | 'reforma'
  | 'pedreiro'
  | 'eletricista'
  | 'encanador'
  | 'pintor'
  | 'mestre_de_obras'
  | 'engenheiro'
  | 'arquiteto'
  | 'construtora'
  | 'manutencao';

export type QuoteStatus = 'novo' | 'em_atendimento' | 'orcamento_enviado' | 'fechado' | 'perdido';
export type QuoteSource = 'carrinho' | 'lista' | 'profissional' | 'frete';

export interface QuoteItem {
  productId: string;
  sku: string;
  name: string;
  unit: string;
  qty: number;
}

export interface StoredFile {
  id: string;
  name: string;
  type: string;
  size: number;
  /** False when the file was validated but not kept (demo mode). */
  stored: boolean;
}

export interface QuoteRequest {
  id: string;
  code: string;
  createdAt: string;
  updatedAt: string;
  status: QuoteStatus;
  source: QuoteSource;
  customer: {
    name: string;
    phone: string;
    email: string | null;
    profile: CustomerProfile;
    company: string | null;
  };
  delivery: {
    mode: 'entrega' | 'retirada';
    cep: string | null;
    district: string | null;
    address: string | null;
    regionId: string | null;
  };
  items: QuoteItem[];
  listText: string | null;
  files: StoredFile[];
  notes: string | null;
  project: { name: string | null; recurring: boolean; volume: string | null } | null;
  internalNotes: string | null;
  /** Records created by the seed: visible unmasked to the demo admin. */
  seed?: boolean;
}

export interface Banner {
  id: string;
  title: string;
  subtitle: string;
  image: string;
  href: string;
  active: boolean;
  order: number;
}

export interface StoreSettings {
  storeName: string;
  descriptor: string;
  slogan: string;
  whatsapp: string | null;
  phoneDisplay: string | null;
  email: string;
  address: { street: string | null; district: string; city: string; state: string };
  hours: { days: string; open: string | null; close: string | null }[];
  theme: { accent: string; accentHover: string; safety: string };
  professionalTerms: string;
  pickupEnabled: boolean;
}

export type EventType = 'view_product' | 'add_to_list' | 'submit_quote' | 'submit_list' | 'whatsapp_click' | 'freight_check' | 'search';

export interface DailyEvents {
  date: string; // YYYY-MM-DD
  counts: Partial<Record<EventType, number>>;
  /** Generated by the demo seed, not real traffic. */
  sample?: boolean;
}

export interface StoreData {
  version: number;
  categories: Category[];
  products: Product[];
  offers: Offer[];
  regions: Region[];
  quotes: QuoteRequest[];
  banners: Banner[];
  settings: StoreSettings;
  events: DailyEvents[];
  sequence: number;
}

export interface TenantConfig {
  id: string;
  demo: boolean;
  brand: { name: string; descriptor: string; slogan: string; shortDescription: string };
  theme: { accent: string; accentHover: string; accentSoft: string; safety: string; ink: string; graphite: string; concrete: string; mineral: string };
  contact: {
    whatsapp: string | null;
    phoneDisplay: string | null;
    email: string;
    address: { street: string | null; district: string; city: string; state: string };
    hours: { days: string; open: string | null; close: string | null }[];
  };
  seo: { city: string; state: string; neighborhoods: string[] };
  regions: Region[];
  policies: { quote: string; delivery: string; professionals: string; privacy: string };
}
